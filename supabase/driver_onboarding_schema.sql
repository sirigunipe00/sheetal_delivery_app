create or replace function public.request_partner_phone_otp(p_phone text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_phone text := regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  v_code text;
  v_debug text := coalesce(current_setting('app.settings.partner_otp_debug', true), '');
begin
  if v_phone !~ '^[6-9][0-9]{9}$' then
    raise exception 'Enter a valid 10-digit mobile number';
  end if;

  v_code := lpad((floor(random() * 1000000))::int::text, 6, '0');

  insert into public.driver_phone_otps (phone, code_hash, attempts, expires_at)
  values (v_phone, crypt(v_code, gen_salt('bf')), 0, now() + interval '10 minutes')
  on conflict (phone) do update
    set code_hash = excluded.code_hash,
        attempts = 0,
        expires_at = excluded.expires_at,
        created_at = now();

  -- TODO: send SMS via MSG91 / Twilio Edge Function.
  if v_debug = 'true' then
    return jsonb_build_object('ok', true, 'debug_otp', v_code);
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.verify_partner_phone_otp(p_phone text, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_phone text := regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  v_row public.driver_phone_otps%rowtype;
begin
  select * into v_row from public.driver_phone_otps where phone = v_phone;
  if v_row.phone is null then
    return jsonb_build_object('ok', false, 'error', 'Request OTP first');
  end if;
  if v_row.expires_at < now() then
    return jsonb_build_object('ok', false, 'error', 'OTP expired. Request a new one');
  end if;
  if v_row.attempts >= 5 then
    return jsonb_build_object('ok', false, 'error', 'Too many attempts. Request a new OTP');
  end if;

  update public.driver_phone_otps set attempts = attempts + 1 where phone = v_phone;

  if v_row.code_hash <> crypt(trim(p_code), v_row.code_hash) then
    return jsonb_build_object('ok', false, 'error', 'Invalid OTP');
  end if;

  delete from public.driver_phone_otps where phone = v_phone;

  if auth.uid() is not null then
    update public.drivers
    set phone = v_phone,
        phone_verified = true,
        updated_at = now()
    where id = auth.uid();
  end if;

  return jsonb_build_object('ok', true, 'phone', v_phone);
end;
$$;

grant execute on function public.request_partner_phone_otp(text) to anon, authenticated;
grant execute on function public.verify_partner_phone_otp(text, text) to anon, authenticated;

-- Submit for admin review
create or replace function public.submit_partner_for_review()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid := auth.uid();
  v_driver public.drivers%rowtype;
begin
  if v_id is null then raise exception 'Not authenticated'; end if;
  select * into v_driver from public.drivers where id = v_id;
  if v_driver.id is null then raise exception 'Partner profile missing'; end if;
  if coalesce(v_driver.phone_verified, false) is not true then
    return jsonb_build_object('ok', false, 'error', 'Verify mobile number with OTP first');
  end if;
  if not exists (select 1 from public.driver_vehicles where driver_id = v_id) then
    return jsonb_build_object('ok', false, 'error', 'Add vehicle details first');
  end if;
  if not exists (
    select 1 from public.driver_documents
    where driver_id = v_id and doc_type in ('driving_licence', 'rc')
    group by driver_id having count(*) >= 2
  ) then
    return jsonb_build_object('ok', false, 'error', 'Upload Driving Licence and RC photos');
  end if;

  update public.drivers
  set verification_status = 'pending_review',
      rejection_reason = null,
      submitted_at = now(),
      is_online = false,
      updated_at = now()
  where id = v_id;

  insert into public.driver_verifications (driver_id, status, notes)
  values (v_id, 'pending_review', 'Submitted by partner');

  return jsonb_build_object('ok', true, 'status', 'pending_review');
end;
$$;

grant execute on function public.submit_partner_for_review() to authenticated;

-- Admin approve / reject (call with service role or as admin profile)
create or replace function public.admin_review_partner(
  p_driver_id uuid,
  p_approve boolean,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text := case when p_approve then 'approved' else 'rejected' end;
begin
  update public.drivers
  set verification_status = v_status,
      rejection_reason = case when p_approve then null else coalesce(p_notes, 'Rejected by admin') end,
      reviewed_at = now(),
      reviewed_by = auth.uid(),
      is_online = case when p_approve then is_online else false end,
      updated_at = now()
  where id = p_driver_id;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'Driver not found');
  end if;

  insert into public.driver_verifications (driver_id, status, notes, reviewed_by)
  values (p_driver_id, v_status, p_notes, auth.uid());

  return jsonb_build_object('ok', true, 'status', v_status);
end;
$$;

grant execute on function public.admin_review_partner(uuid, boolean, text) to authenticated;

-- Block going online unless approved
create or replace function public.drivers_require_approval()
returns trigger
language plpgsql
as $$
begin
  if new.is_online = true and coalesce(old.is_online, false) = false then
    if coalesce(new.verification_status, 'draft') <> 'approved' then
      raise exception 'Admin approval required before going online';
    end if;
    if coalesce(new.phone_verified, false) is not true then
      raise exception 'Verify mobile number before going online';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists drivers_require_approval_trg on public.drivers;
create trigger drivers_require_approval_trg
  before update of is_online on public.drivers
  for each row execute function public.drivers_require_approval();

-- Only approved partners receive nearby order alerts
create or replace function public.notify_online_drivers()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  radius_km constant double precision := 8;
  center_lat double precision;
  center_lng double precision;
begin
  if new.status is distinct from 'placed' then
    return new;
  end if;

  center_lat := new.delivery_lat;
  center_lng := new.delivery_lng;
  if center_lat is null or center_lng is null then
    select s.latitude, s.longitude into center_lat, center_lng
    from public.delivery_stores s where s.id = 1;
  end if;

  insert into public.driver_order_alerts (driver_id, order_id, status, distance_km)
  select
    d.id,
    new.id,
    'pending',
    round(public.haversine_km(center_lat, center_lng, d.latitude, d.longitude)::numeric, 2)
  from public.drivers d
  where d.is_online = true
    and coalesce(d.verification_status, 'approved') = 'approved'
    and coalesce(d.phone_verified, true) = true
    and d.latitude is not null
    and d.longitude is not null
    and center_lat is not null
    and center_lng is not null
    and public.haversine_km(center_lat, center_lng, d.latitude, d.longitude) <= radius_km
  on conflict (driver_id, order_id) do nothing;

  begin
    perform public.request_nearby_driver_push(new.id);
  exception when others then null;
  end;

  return new;
end;
$$;

