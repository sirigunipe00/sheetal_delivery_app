-- Sheetal delivery partner setup.
-- Run once in the Supabase SQL editor for project kmiuxdaaznmzdbhmrmmh.
-- Safe to run again.

begin;

create table if not exists public.drivers (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null,
  phone text not null,
  email text,
  vehicle_number text,
  is_online boolean not null default false,
  latitude double precision,
  longitude double precision,
  fcm_token text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.orders add column if not exists driver_id uuid;
alter table public.orders add column if not exists delivery_lat double precision;
alter table public.orders add column if not exists delivery_lng double precision;

create index if not exists orders_driver_status_idx
  on public.orders (driver_id, status);

create index if not exists drivers_online_idx
  on public.drivers (is_online);

create table if not exists public.driver_order_alerts (
  id bigint generated by default as identity primary key,
  driver_id uuid not null references public.drivers (id) on delete cascade,
  order_id uuid not null references public.orders (id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists driver_order_alerts_driver_idx
  on public.driver_order_alerts (driver_id, created_at desc);

alter table public.drivers enable row level security;
alter table public.driver_order_alerts enable row level security;

-- SECURITY DEFINER helper — never put "select from drivers" inside a drivers policy.
create or replace function public.is_sheetal_driver()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.drivers d where d.id = auth.uid()
  );
$$;
revoke all on function public.is_sheetal_driver() from public;
grant execute on function public.is_sheetal_driver() to authenticated;

drop policy if exists "Drivers manage own profile" on public.drivers;
create policy "Drivers manage own profile"
  on public.drivers
  for all
  to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

drop policy if exists "Drivers read delivery orders" on public.orders;
create policy "Drivers read delivery orders"
  on public.orders
  for select
  to authenticated
  using (public.is_sheetal_driver());

drop policy if exists "Drivers update delivery orders" on public.orders;
create policy "Drivers update delivery orders"
  on public.orders
  for update
  to authenticated
  using (public.is_sheetal_driver())
  with check (public.is_sheetal_driver());

drop policy if exists "Drivers read own alerts" on public.driver_order_alerts;
create policy "Drivers read own alerts"
  on public.driver_order_alerts
  for select
  to authenticated
  using (driver_id = auth.uid());

grant select, insert, update on public.drivers to authenticated;
grant select, update on public.orders to authenticated;
grant select on public.driver_order_alerts to authenticated;

commit;

-- Line items stay readable by the partner who is delivering them.
do $$
begin
  if to_regclass('public.order_items') is not null then
    execute 'alter table public.order_items enable row level security';
    execute 'drop policy if exists "Drivers read order items" on public.order_items';
    execute 'create policy "Drivers read order items" on public.order_items for select to authenticated using (exists (select 1 from public.drivers d where d.id = auth.uid()))';
    execute 'grant select on public.order_items to authenticated';
  end if;
end $$;

-- Create the partner row even when email confirmation delays the first session.
create or replace function public.handle_new_driver()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.raw_user_meta_data->>'role' = 'driver' then
    insert into public.drivers (id, full_name, phone, email, vehicle_number)
    values (
      new.id,
      coalesce(new.raw_user_meta_data->>'full_name', 'Partner'),
      coalesce(new.raw_user_meta_data->>'phone', ''),
      new.email,
      new.raw_user_meta_data->>'vehicle_number'
    )
    on conflict (id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_driver on auth.users;
create trigger on_auth_user_created_driver
  after insert on auth.users
  for each row execute function public.handle_new_driver();

-- Alert only partners who are online at the moment the customer places the order.
create or replace function public.notify_online_drivers()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from 'placed' then
    return new;
  end if;

  insert into public.driver_order_alerts (driver_id, order_id)
  select d.id, new.id
  from public.drivers d
  where d.is_online = true;

  return new;
end;
$$;

drop trigger if exists orders_notify_online_drivers on public.orders;
create trigger orders_notify_online_drivers
  after insert on public.orders
  for each row execute function public.notify_online_drivers();

-- Realtime so the partner app can show a new order immediately.
